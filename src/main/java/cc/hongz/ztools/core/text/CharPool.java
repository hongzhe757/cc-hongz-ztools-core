package cc.hongz.ztools.core.text;

/**
 * 常用字符常量
 * @see StrPool
 * @author looly
 * @since 5.6.3
 */
public interface CharPool {
	char SPACE = ' ';
	char TAB = '	';
	char DOT = '.';
	char SLASH = '/';
	char BACKSLASH = '\\';
	char CR = '\r';
	char LF = '\n';
	char DASHED = '-';
	char UNDERLINE = '_';
	char COMMA = ',';
	char DELIM_START = '{';
	char DELIM_END = '}';
	char BRACKET_START = '[';
	char BRACKET_END = ']';
	char DOUBLE_QUOTES = '"';
	char SINGLE_QUOTE = '\'';
	char AMP = '&';
	char COLON = ':';
	char AT = '@';
}
